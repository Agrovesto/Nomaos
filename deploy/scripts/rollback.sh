#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# rollback.sh — put traffic back on the previous slot
#
#   rollback.sh --app nomaos-api                 # flip to the idle slot
#   rollback.sh --app nomaos-api --image <ref>   # restart idle slot on a
#                                                # known-good image, then flip
#
# Fast path: if the previous slot is still running (deploy --keep-old, or a
# flip that just happened), this is a config rewrite + nginx reload. Seconds.
# ─────────────────────────────────────────────────────────────────────────────
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"

APP_NAME=""
IMAGE=""
HEALTH_TIMEOUT="${HEALTH_TIMEOUT:-180}"

usage() {
  cat <<'EOF'
Usage: rollback.sh --app <name> [--image <ref>] [--timeout <sec>]

  --app   <name>   nomaos-api | nomaos-app2
  --image <ref>    Image to (re)start the idle slot with. Required when the
                   idle slot is not still running.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --app)     APP_NAME="${2:?}"; shift 2 ;;
    --image)   IMAGE="${2:?}"; shift 2 ;;
    --timeout) HEALTH_TIMEOUT="${2:?}"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; die "unknown argument: $1" ;;
  esac
done

[[ -n "$APP_NAME" ]] || { usage >&2; exit 2; }

require_docker
load_app_env "$APP_NAME"

APP_PORT="${APP_PORT:-5007}"
UPSTREAM_NAME="${UPSTREAM_NAME:-${APP_NAME//-/_}}"
UPSTREAM_FILE="$NOMAOS_STATE_DIR/nginx/upstreams/${UPSTREAM_NAME}.conf"
NGINX_CONTAINER="${NGINX_CONTAINER:-nomaos-nginx}"

ACTIVE="$(get_active_slot "$APP_NAME")"
TARGET="$(other_slot "$ACTIVE")"
TARGET_CONTAINER="${APP_NAME}-${TARGET}"

info "rolling back $APP_NAME: $ACTIVE -> $TARGET"

state="$(container_state "$TARGET_CONTAINER")"
if [[ "$state" != "running" ]]; then
  [[ -n "$IMAGE" ]] || die "$TARGET_CONTAINER is '$state' and no --image given. \
Pass the image you want to roll back to (see: docker images | grep nomaos)."

  info "starting $TARGET slot from $IMAGE"
  IMAGE="$IMAGE" APP_NAME="$APP_NAME" SLOT="$TARGET" APP_PORT="$APP_PORT" \
  COMMIT_SHA="rollback" NOMAOS_STATE_DIR="$NOMAOS_STATE_DIR" \
  docker compose -p "${APP_NAME}-${TARGET}" \
    -f "$COMPOSE_DIR/docker-compose.app.yml" up -d --no-build

  wait_for_health "$TARGET_CONTAINER" "$HEALTH_TIMEOUT" \
    || die "rollback target never became healthy — staying on $ACTIVE"
else
  ok "$TARGET_CONTAINER already running"
fi

info "rewriting upstream"
tmp="$(mktemp)"
cat > "$tmp" <<EOF
# Generated by rollback.sh — $(date -u +%Y-%m-%dT%H:%M:%SZ)
# app=$APP_NAME slot=$TARGET (ROLLBACK)
upstream ${UPSTREAM_NAME} {
    server ${APP_NAME}-${TARGET}:${APP_PORT} max_fails=2 fail_timeout=5s;
    keepalive 32;
}
EOF
mv "$tmp" "$UPSTREAM_FILE"
chmod 644 "$UPSTREAM_FILE"

docker exec "$NGINX_CONTAINER" nginx -t >/dev/null 2>&1 \
  || die "nginx config invalid after rewrite — NOT reloading"
docker exec "$NGINX_CONTAINER" nginx -s reload

set_active_slot "$APP_NAME" "$TARGET"

ok "rolled back — traffic now on $TARGET"
info "the bad slot ($ACTIVE) is left running for inspection:"
printf '    docker logs --tail 200 %s-%s\n' "$APP_NAME" "$ACTIVE"
printf '    docker compose -p %s-%s -f %s/docker-compose.app.yml down   # when done\n' \
  "$APP_NAME" "$ACTIVE" "$COMPOSE_DIR"
